/* ==========================================================
   SITE SCRIPT – theme, menu, favourites, forms, property filters,
   agent search and the property gallery. Property, agent and location
   pages are plain HTML generated by tools/build.py, so this file only
   adds behaviour to markup that already exists.
   ========================================================== */
(() => {
const $ = (s, r = document) => r.querySelector(s);
const $$ = (s, r = document) => [...r.querySelectorAll(s)];

/* ---------- Theme toggle (light / dark) ----------
   The inline script in every <head> sets data-theme before first paint (no flash).
   The choice is saved in localStorage ("theme") and shared by every page. */
const root = document.documentElement, tt = $('#tt');
const setTheme = (t, persist) => {
  root.setAttribute('data-theme', t);
  if (persist) { try { localStorage.setItem('theme', t); } catch (e) {} }
  if (tt) {
    tt.setAttribute('aria-label', t == 'dark' ? 'Switch to light mode' : 'Switch to dark mode');
    tt.title = t == 'dark' ? 'Switch to light mode' : 'Switch to dark mode';
  }
};
setTheme(root.getAttribute('data-theme') == 'dark' ? 'dark' : 'light', false);
if (tt) tt.onclick = () => setTheme(root.getAttribute('data-theme') == 'dark' ? 'light' : 'dark', true);
window.addEventListener('storage', e => { if (e.key == 'theme' && (e.newValue == 'light' || e.newValue == 'dark')) setTheme(e.newValue, false); }); // other open tabs

/* ---------- Mobile menu ---------- */
const bg = $('#bg'), nv = $('#nv');
if (bg) bg.onclick = () => bg.setAttribute('aria-expanded', nv.classList.toggle('open'));

/* ---------- Favourites (saved in the browser) ---------- */
let fav = new Set();
try { fav = new Set(JSON.parse(localStorage.getItem('fav') || '[]')); } catch (e) {}
const save = () => { try { localStorage.setItem('fav', JSON.stringify([...fav])); } catch (e) {} };
const paint = b => {
  const on = fav.has(b.dataset.fav);
  b.classList.toggle('on', on);
  b.textContent = b.dataset.long ? (on ? '♥ Saved' : '♡ Save') : (on ? '♥' : '♡');
};
const initFav = root => $$('[data-fav]', root).forEach(b => {
  paint(b);
  b.onclick = e => {
    e.preventDefault(); e.stopPropagation();
    const s = b.dataset.fav;
    fav.has(s) ? fav.delete(s) : fav.add(s);
    save(); $$('[data-fav="' + s + '"]').forEach(paint);
  };
});
initFav(document);

/* ---------- Forms ---------- */
const check = i => {
  if (i.required && !i.value.trim()) return 'Required.';
  if (i.type == 'email' && i.value && !/^\S+@\S+\.\S+$/.test(i.value)) return 'Enter a valid email.';
  if (i.type == 'tel' && i.value && i.value.replace(/\D/g, '').length < 7) return 'Enter a valid phone number.';
  return '';
};
const initForms = root => $$('form[novalidate]', root).forEach(f => f.onsubmit = e => {
  e.preventDefault();
  let ok = true;
  $$('[name]', f).forEach(i => {
    const m = check(i), er = $('#' + i.id + '-e');
    if (er) er.textContent = m;
    i.setAttribute('aria-invalid', !!m);
    if (m) ok = false;
  });
  if (!ok) return;
  if (f.getAttribute('action')) f.submit(); // real form service set in config.js
  else f.innerHTML = `<div class="ok" role="status">${f.dataset.ok || 'Thank you.'}</div>`; // demo mode
});
initForms(document);
const qs = new URLSearchParams(location.search);
if ($('#vl-addr') && qs.get('addr')) $('#vl-addr').value = qs.get('addr');

/* ---------- Property list: filter, sort, load more ---------- */
const ff = $('#ff');
if (ff) {
  const list = $('#plist'), cards = $$('.prop', list), per = +list.dataset.per, preset = list.dataset.list || '';
  const keys = ['q', 'list', 'type', 'min', 'max', 'beds', 'baths', 'area', 'status'];
  const LBL = { q: 'Location', list: 'Listing', type: 'Type', min: 'Min price', max: 'Max price', beds: 'Beds', baths: 'Baths', area: 'Area', status: 'Status' };
  const el = k => $('#f-' + k);
  let shown = per, sort = 'rec';
  keys.forEach(k => { if (el(k) && qs.has(k)) el(k).value = qs.get(k); });

  const read = () => ({
    q: (el('q').value || '').trim(), list: preset || (el('list') ? el('list').value : ''), type: el('type').value,
    min: +el('min').value, max: +el('max').value || 1e12, beds: +el('beds').value, baths: +el('baths').value,
    area: +el('area').value, status: el('status').value
  });
  const run = () => {
    const F = read(), q = F.q.toLowerCase();
    const r = cards.filter(c => { const x = c.dataset; return (!q || x.search.includes(q)) && (!F.list || x.listing == F.list) && (!F.type || x.type == F.type) && +x.price >= F.min && +x.price <= F.max && +x.beds >= F.beds && +x.baths >= F.baths && +x.area >= F.area && (!F.status || x.status == F.status); });
    const [k, dir] = { rec: ['rank', 1], lo: ['price', 1], hi: ['price', -1], new: ['age', 1], big: ['area', -1] }[sort];
    r.sort((a, b) => (a.dataset[k] - b.dataset[k]) * dir);
    cards.forEach(c => c.hidden = true);
    r.forEach((c, i) => { c.hidden = i >= shown; list.appendChild(c); });
    $('#count').textContent = r.length + (r.length == 1 ? ' property' : ' properties');
    $('#more').hidden = shown >= r.length;
    $('#none').hidden = r.length > 0;
    const chips = $('#chips'); chips.textContent = '';
    Object.entries(F).forEach(([key, v]) => {
      if (!v || v == 1e12 || (key == 'list' && preset)) return;
      const s = document.createElement('span'); s.className = 'chip';
      s.textContent = LBL[key] + ': ' + (key == 'min' || key == 'max' ? '₹' + (+v).toLocaleString('en-IN') : v);
      chips.appendChild(s);
    });
  };
  const url = () => {
    const p = new URLSearchParams(), F = read();
    Object.entries(F).forEach(([k, v]) => { if (v && v != 1e12 && !(k == 'list' && preset)) p.set(k, v); });
    history.replaceState(null, '', location.pathname + (p.toString() ? '?' + p : ''));
  };
  ff.onsubmit = e => { e.preventDefault(); shown = per; run(); url(); };
  const clear = () => { ff.reset(); shown = per; run(); history.replaceState(null, '', location.pathname); };
  $('#clr').onclick = clear; $('#clr2').onclick = clear;
  $('#so').onchange = e => { sort = e.target.value; run(); };
  $('#more').onclick = () => { shown += per; run(); };
  run();
}

/* ---------- Agents search ---------- */
const aq = $('#aq');
if (aq) aq.oninput = () => {
  const q = aq.value.toLowerCase().trim(); let n = 0;
  $$('#ag .card').forEach(c => { const m = c.dataset.search.includes(q); c.hidden = !m; if (m) n++; });
  $('#ag-none').hidden = n > 0;
};

/* ==========================================================
   PROPERTY GALLERY – main image, prev/next, thumbnails, fullscreen, share.
   The markup is rendered at build time; thumbnails carry data-full / data-alt.
   ========================================================== */
const gm = $('#gm');
if (gm) {
  const main = $('img', gm), th = $$('.thumbs button'), cnt = $('#gcount');
  const imgs = th.length ? th.map(b => ({ src: b.dataset.full, alt: b.dataset.alt })) : [{ src: main.getAttribute('src'), alt: main.alt }];
  let cur = 0;
  const go = i => {
    cur = (i + imgs.length) % imgs.length;
    main.src = imgs[cur].src; main.alt = imgs[cur].alt;
    th.forEach((b, j) => { b.classList.toggle('on', j == cur); b.setAttribute('aria-current', j == cur); });
    if (cnt) cnt.textContent = (cur + 1) + ' / ' + imgs.length;
  };
  th.forEach((b, i) => b.onclick = () => go(i));
  $$('.g-nav').forEach(b => b.onclick = e => { e.stopPropagation(); go(cur + +b.dataset.step); });
  if (th.length) go(0);
  const lightbox = () => {
    const d = document.createElement('div');
    d.className = 'lb'; d.setAttribute('role', 'dialog'); d.setAttribute('aria-label', 'Image viewer');
    d.innerHTML = '<div class="in"><div id="lbi"></div><p><button class="btn" id="pv" type="button">Prev</button> <button class="btn" id="nx" type="button">Next</button> <button class="btn out light" id="cl" type="button">Close</button></p></div>';
    document.body.appendChild(d);
    const draw = () => { $('#lbi').innerHTML = ''; const i = document.createElement('img'); i.src = main.src; i.alt = main.alt; $('#lbi').appendChild(i); };
    const move = n => { go(cur + n); draw(); };
    const key = e => { if (e.key == 'Escape') close(); if (e.key == 'ArrowRight') move(1); if (e.key == 'ArrowLeft') move(-1); };
    const close = () => { d.remove(); document.removeEventListener('keydown', key); gm.focus(); };
    document.addEventListener('keydown', key);
    $('#pv').onclick = () => move(-1); $('#nx').onclick = () => move(1); $('#cl').onclick = close;
    draw(); $('#cl').focus();
  };
  gm.onclick = lightbox;
  gm.onkeydown = e => { if (e.key == 'Enter') lightbox(); if (e.key == 'ArrowRight') go(cur + 1); if (e.key == 'ArrowLeft') go(cur - 1); };
  const sh = $('#sh');
  if (sh) sh.onclick = async () => {
    try {
      if (navigator.share) await navigator.share({ title: document.title, url: location.href });
      else { await navigator.clipboard.writeText(location.href); sh.textContent = 'Link copied'; }
    } catch (e) { sh.textContent = 'Copy the URL'; }
  };
}
const visit = $('#visit');
if (visit) visit.onclick = e => {
  const f = $('#vf'); if (!f) return;
  e.preventDefault(); f.scrollIntoView({ behavior: 'smooth', block: 'center' });
  const i = $('input', f); if (i) i.focus({ preventScroll: true });
};
})();
